/** A node in the description of a Faust DSP's user interface, as declared by its buildUserInterface() method.
 * Groups (tab/horizontal/vertical boxes) have children, widgets have a zone.
 * This is what UI builders such as IGraphicsFaustUI use to create controls, so they never need to touch the DSP. */
struct FaustUIItem
{
  enum class EType { TabBox, HBox, VBox, Button, CheckButton, HSlider, VSlider, NumEntry, HBargraph, VBargraph, Soundfile };

  EType type = EType::VBox;
  std::string label; // the widget/group label, with Faust's anonymous "0x00" groups mapped to ""
  std::string path;  // the full path of the item, e.g. "/synth/osc/freq"
  FAUSTFLOAT* zone = nullptr;
  double init = 0., min = 0., max = 1., step = 0.;

  int paramIdx = kNoParameter; // index of the IPlug parameter linked to this widget (see IPlugFaust::CreateIPlugParameters)
  int ctrlTag = kNoTag;        // for bargraphs: the control tag that values are sent to

  // metadata
  bool hidden = false;
  bool knob = false;
  bool led = false;
  bool numerical = false;
  bool menu = false;
  bool radio = false;
  std::string unit;
  std::string tooltip;
  std::vector<std::pair<std::string, double>> options; // menu/radio items

  std::vector<FaustUIItem> children;

  bool IsGroup() const { return type == EType::TabBox || type == EType::HBox || type == EType::VBox; }
  bool IsBargraph() const { return type == EType::HBargraph || type == EType::VBargraph; }
};

/** IPlugFaust is the base class for hosting a Faust DSP inside an iPlug2 plug-in.
 * It maps the Faust DSP's widgets to IPlug parameters, routes MIDI to the DSP (including polyphony via the "[nvoices:N]" option),
 * sends bargraph values to the editor and keeps a description of the Faust UI that UI builders can use.
 *
 * There are two implementations which share this interface:
 * - FaustGen (IPlugFaustGen.h) compiles a .dsp file at runtime with the libfaust interpreter backend, and can recompile it when the file changes.
 * - Faust_<Class> is generated by the faust compiler using the IPlugFaust_arch.cpp architecture file, for statically compiled (release) builds.
 * Use the FAUST_BLOCK macro (IPlugFaustGen.h) to switch between the two using the FAUST_COMPILED preprocessor macro. */
class IPlugFaust : public UI, public MetaDataUI
{
public:
  static constexpr int kDefaultCtrlTagStart = 1000;

  /** @param name A name for the DSP, used for logging
   * @param nVoices Number of polyphonic voices to use if the DSP doesn't declare "[nvoices:N]" in its options metadata. Values < 2 mean monophonic.
   * @param ctrlTagStart The first control tag used for bargraphs. Bargraphs are given consecutive tags in the order they are declared. */
  IPlugFaust(const char* name, int nVoices = 0, int ctrlTagStart = kDefaultCtrlTagStart);
  virtual ~IPlugFaust();

  IPlugFaust(const IPlugFaust&) = delete;
  IPlugFaust& operator=(const IPlugFaust&) = delete;

  /** Create the DSP. Call this once after construction (and after SetMaxChannelCount) */
  virtual void Init() = 0;

  /** Tell IPlugFaust the maximum number of channels the plug-in provides, if the DSP needs more it will output silence
   * @param maxNInputs Maximum number of input channels
   * @param maxNOutputs Maximum number of output channels */
  void SetMaxChannelCount(int maxNInputs, int maxNOutputs);

  /** Call this from the plug-in's OnReset() */
  void SetSampleRate(double sampleRate);

  /** Call this from the plug-in's ProcessMidiMsg() */
  void ProcessMidiMsg(const IMidiMsg& msg);

  /** Call this from the plug-in's ProcessBlock(). Unused output channels are cleared. */
  void ProcessBlock(sample** inputs, sample** outputs, int nFrames);

  /** @return \c true if a DSP has been created and can be processed (it fits the channel count and doesn't use soundfiles) */
  bool IsReady() const { return mDSP != nullptr && !mChannelCountError && !mHasSoundfile; }

  int NInputs() const { return mDSP ? mDSP->getNumInputs() : 0; }
  int NOutputs() const { return mDSP ? mDSP->getNumOutputs() : 0; }
  int GetMaxNInputs() const { return mMaxNInputs; }
  int GetMaxNOutputs() const { return mMaxNOutputs; }

#pragma mark - Parameters

  /** @return The number of Faust widgets that are mapped to parameters (buttons, checkboxes, sliders and numerical entries) */
  int NParams() const { return static_cast<int>(mParams.size()); }

  /** Initialize the plug-in's parameters startIdx...startIdx+NParams() from the Faust widgets, and link them.
   * The plug-in must have enough parameters, so for a JIT compiled DSP that may change, allocate some spare ones.
   * After linking, the IPlug parameter values are applied to the DSP in SetParameterValueNormalised().
   * @param pPlug The plug-in
   * @param startIdx The index of the first plug-in parameter to use
   * @param endIdx The index after the last Faust parameter to link, or -1 for all of them
   * @param setToDefault If \c true the parameters are set to their default values, otherwise the current normalized values are kept
   * @return startIdx, or -1 if the DSP has no parameters */
  int CreateIPlugParameters(IPlugAPIBase* pPlug, int startIdx = 0, int endIdx = -1, bool setToDefault = true);

  /** If plugParamIdx is linked to a Faust widget, update its zone from the plug-in's parameter value. Call this from the plug-in's OnParamChange().
   * @return \c true if the parameter belongs to this DSP */
  bool OnParamChange(int plugParamIdx);

  /** Set a Faust widget's value via its parameter index (0...NParams()-1)
   * @param faustParamIdx The index of the Faust parameter
   * @param normalizedValue The normalized [0, 1] value */
  void SetParameterValueNormalised(int faustParamIdx, double normalizedValue);

  /** Set a Faust widget's value via its parameter index (0...NParams()-1)
   * @param faustParamIdx The index of the Faust parameter
   * @param value The non-normalized value */
  void SetParameterValue(int faustParamIdx, double value);

  /** Set a Faust widget's value via its label or full path (e.g. "freq" or "/synth/freq"). This doesn't update linked IPlug parameters.
   * @param labelOrPath The label or full path of the widget
   * @param value The non-normalized value */
  void SetParameterValue(const char* labelOrPath, double value);

  /** Apply the values of all the parameters to the DSP (e.g. after dsp::init() has reset the zones) */
  void SyncFaustParams();

  /** @return The Faust parameter index for a zone, or kNoParameter */
  int GetFaustParamIdxForZone(FAUSTFLOAT* zone) const;

  /** @return The IPlug parameter index linked to a Faust parameter, or kNoParameter if not linked */
  int GetPlugParamIdx(int faustParamIdx) const;

#pragma mark - UI

  /** @return The description of the Faust UI (the root is the top-level group), which is rebuilt every time the DSP changes */
  const FaustUIItem& GetUIRoot() const { return mUIRoot; }

  /** @return A JSON description of the DSP, as generated by Faust's JSONUI */
  const char* GetJSON() const { return mJSON.c_str(); }

  /** Calls buildUserInterface() and metadata() on the DSP, to build a Faust UI. Only call this on the main thread. */
  void BuildUI(UI* pUI);

#pragma mark - Faust UI interface (used internally)

  void openTabBox(const char* label) override;
  void openHorizontalBox(const char* label) override;
  void openVerticalBox(const char* label) override;
  void closeBox() override;
  void addButton(const char* label, FAUSTFLOAT* zone) override;
  void addCheckButton(const char* label, FAUSTFLOAT* zone) override;
  void addVerticalSlider(const char* label, FAUSTFLOAT* zone, FAUSTFLOAT init, FAUSTFLOAT min, FAUSTFLOAT max, FAUSTFLOAT step) override;
  void addHorizontalSlider(const char* label, FAUSTFLOAT* zone, FAUSTFLOAT init, FAUSTFLOAT min, FAUSTFLOAT max, FAUSTFLOAT step) override;
  void addNumEntry(const char* label, FAUSTFLOAT* zone, FAUSTFLOAT init, FAUSTFLOAT min, FAUSTFLOAT max, FAUSTFLOAT step) override;
  void addHorizontalBargraph(const char* label, FAUSTFLOAT* zone, FAUSTFLOAT min, FAUSTFLOAT max) override;
  void addVerticalBargraph(const char* label, FAUSTFLOAT* zone, FAUSTFLOAT min, FAUSTFLOAT max) override;
  void addSoundfile(const char* label, const char* filename, Soundfile** sfZone) override;
  void declare(FAUSTFLOAT* zone, const char* key, const char* value) override;

protected:
  /** Takes ownership of a newly created DSP, wraps it for polyphony if required, (re)builds the parameters and UI description and swaps it in.
   * Everything is prepared first. The swap itself only exchanges pointers, while the audio thread outputs silence (at most one block),
   * so it is safe to call while processing. Call it on the main thread.
   * @param pMonoDSP The new DSP instance */
  void SetDSP(::dsp* pMonoDSP);

  /** Destroys the DSP. Subclasses that own something the DSP depends on (e.g. the factory that created it) must call this in their destructor */
  void ReleaseDSP();

  /** If SetDSP() re-initialized the linked plug-in parameters (i.e. the DSP was replaced), tell the host to re-read the parameter details.
   * Call this on the main thread, after the plug-in has finished updating its parameters */
  void InformHostIfParamsChanged();

  WDL_String mName;

private:
  struct Param
  {
    std::unique_ptr<IParam> param = std::make_unique<IParam>(); // describes the parameter, copied to the plug-in's IParam in CreateIPlugParameters()
    FAUSTFLOAT* zone = nullptr;
    std::vector<double> enumValues; // for menus and radio buttons: the Faust value for each enum index
    std::string path;
  };

  struct Bargraph
  {
    FAUSTFLOAT* zone = nullptr;
    double min = 0.;
    double max = 1.;
    int ctrlTag = kNoTag;
    bool hidden = false; // [hidden:1] or in a hidden group: IGraphicsFaustUI creates no control, so no values are sent
    double lastSentValue = -1.;
  };

  /** Lets the audio thread (and other threads that touch the DSP) use the DSP without locking, while the main thread replaces it.
   * Users never block: TryEnter() fails while the DSP is being replaced and the caller skips its work.
   * The replacing thread waits until current users have finished (at most one audio block), and keeps new ones out until it is done. */
  class DSPGuard
  {
  public:
    bool TryEnter()
    {
      mNUsers.fetch_add(1, std::memory_order_seq_cst);

      if (mReplacing.load(std::memory_order_seq_cst))
      {
        mNUsers.fetch_sub(1, std::memory_order_release);
        return false;
      }

      return true;
    }

    void Exit() { mNUsers.fetch_sub(1, std::memory_order_release); }

    void BeginReplace()
    {
      mReplaceMutex.lock(); // only serializes replacing threads, the audio thread never takes it
      mReplacing.store(true, std::memory_order_seq_cst);

      while (mNUsers.load(std::memory_order_seq_cst) > 0)
        std::this_thread::yield();
    }

    void EndReplace()
    {
      mReplacing.store(false, std::memory_order_release);
      mReplaceMutex.unlock();
    }

  private:
    std::atomic<int> mNUsers {0};
    std::atomic<bool> mReplacing {false};
    std::mutex mReplaceMutex;
  };

  /** RAII user of the DSP, check IsEntered() */
  class ScopedDSPUser
  {
  public:
    ScopedDSPUser(DSPGuard& guard) : mGuard(guard), mEntered(guard.TryEnter()) {}
    ~ScopedDSPUser() { if (mEntered) mGuard.Exit(); }
    bool IsEntered() const { return mEntered; }
  private:
    DSPGuard& mGuard;
    bool mEntered;
  };

  /** RAII replacement of the DSP */
  class ScopedDSPReplace
  {
  public:
    ScopedDSPReplace(DSPGuard& guard) : mGuard(guard) { mGuard.BeginReplace(); }
    ~ScopedDSPReplace() { mGuard.EndReplace(); }
  private:
    DSPGuard& mGuard;
  };

  void BuildDescription(::dsp* pDSP);
  void OpenGroup(FaustUIItem::EType type, const char* label);
  FaustUIItem& AddItem(FaustUIItem::EType type, const char* label, FAUSTFLOAT* zone);
  void AddBargraph(FaustUIItem::EType type, const char* label, FAUSTFLOAT* zone, FAUSTFLOAT min, FAUSTFLOAT max);
  void AddParam(FaustUIItem& item, IParam::EParamType type);
  void RelinkParams();
  void WriteZone(int faustParamIdx, double value);
  void WriteZoneUnguarded(int faustParamIdx, double value);
  void OnUITimer(Timer& timer);

  int mNVoices;
  int mCtrlTagStart;
  int mMaxNInputs = -1;
  int mMaxNOutputs = -1;
  bool mChannelCountError = false;
  bool mHasSoundfile = false; // soundfiles are not supported
  double mSampleRate = 0.;

  // Members used on the audio thread are only replaced while mDSPGuard keeps it out
  DSPGuard mDSPGuard;
  std::unique_ptr<iplug2_midi_handler> mMidiHandler;
  std::unique_ptr<MidiUI> mMidiUI;
  std::unique_ptr<::dsp> mDSP;
  std::vector<Param> mParams;
  std::vector<Bargraph> mBargraphs;
  FaustUIItem mUIRoot;
  std::string mJSON;

  // The description of a new DSP is built into these (by the Faust UI interface methods), then swapped in
  std::vector<Param> mNewParams;
  std::vector<Bargraph> mNewBargraphs;
  FaustUIItem mNewUIRoot;
  bool mNewHasSoundfile = false;
  std::vector<FaustUIItem*> mGroupStack;

  IPlugAPIBase* mPlug = nullptr;
  // Set on the main thread, read by OnParamChange() on any thread
  std::atomic<int> mPlugParamStartIdx {-1}; // < 0 means not linked
  std::atomic<int> mPlugParamEndIdx {-1};
  bool mParamsChanged = false; // set when linked parameters were re-initialized

  std::unique_ptr<Timer> mUITimer;
};

